import { AxeBuilder } from "@axe-core/playwright";
import { readFile } from "node:fs/promises";
import { test, expect } from "@playwright/test";
test("engineered ecosystem controls, observations and responsive layout", async ({ page }, testInfo) => {
  const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("/ecosystem/");
  await expect(page.getByRole("button", { name: "Resume", exact: true })).toBeVisible();
  await expect(page.getByRole("navigation", { name: "Creative prototypes" }).getByRole("link")).toHaveCount(2);
  await page.getByRole("button", { name: "Step once" }).click();
  await expect(page.locator("#clock")).toContainText("Tick 1");
  await page.getByRole("button", { name: "Plant protected family" }).click();
  await expect(page.locator("#events")).toContainText("Manual introduction: 24 Protected");
  await page.getByRole("button", { name: "Plant hunter", exact: true }).click();
  await page.getByRole("button", { name: "Make a local drought" }).click();
  await expect(page.locator("#climate")).toContainText("120 ticks left");
  await page.getByLabel("Mutation", { exact: true }).uncheck();
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Save observation JSON" }).click();
  const saved = await download;
  expect(saved.suggestedFilename()).toBe("ecosystem-1101-1.json");
  const snapshot = JSON.parse(await readFile((await saved.path())!, "utf8"));
  expect(snapshot.tick).toBe(1); expect(snapshot.settings.mutation).toBe(false);
  expect(snapshot.retention).toMatchObject({ sampleLimit: 300, noticeLimit: 100, droppedSamples: 0 });
  expect(snapshot.notices.some((n: { text: string }) => n.text.includes("Manual introduction: 24 Hunter"))).toBe(true);
  expect(snapshot.cells).toHaveLength(96 * 96);
  await page.screenshot({ path: testInfo.outputPath("ecosystem-desktop.png"), fullPage: true });
  await page.getByRole("button", { name: "Replant" }).click();
  await expect(page.locator("#clock")).toContainText("Tick 0");
  await expect(page.locator("#events")).not.toContainText("Manual introduction");
  await page.getByLabel("Mutation", { exact: true }).check();
  await page.getByLabel("Tempo").selectOption("120");
  await page.getByRole("button", { name: "Resume", exact: true }).click();
  await expect(page.locator("#clock")).not.toContainText("Tick 0");
  await expect(page.locator("#events")).toContainText("Staged introduction: 24 Hunter", { timeout: 20000 });
  await page.getByRole("button", { name: "Pause", exact: true }).click();
  await page.screenshot({ path: testInfo.outputPath("ecosystem-evolved.png"), fullPage: true });
  await page.getByRole("button", { name: "Resume", exact: true }).click();
  await page.evaluate(() => {
    Object.defineProperty(document, "hidden", { configurable: true, value: true });
    Object.defineProperty(document, "visibilityState", { configurable: true, value: "hidden" });
    document.dispatchEvent(new Event("visibilitychange"));
  });
  await expect.poll(() => page.evaluate(() => document.visibilityState)).toBe("hidden");
  await expect(page.getByRole("button", { name: "Resume", exact: true })).toBeVisible();
  const hiddenTick = await page.locator("#clock").textContent();
  await page.evaluate(() => {
    Object.defineProperty(document, "hidden", { configurable: true, value: false });
    Object.defineProperty(document, "visibilityState", { configurable: true, value: "visible" });
    document.dispatchEvent(new Event("visibilitychange"));
  });
  await expect.poll(() => page.evaluate(() => document.visibilityState)).toBe("visible");
  await page.waitForTimeout(350);
  await expect(page.locator("#clock")).toHaveText(hiddenTick!);
  await expect(page.getByRole("button", { name: "Resume", exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("ecosystem-mobile.png"), fullPage: true });
  const accessibility = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
  expect(accessibility.violations).toEqual([]);
  expect(errors).toEqual([]);
});
